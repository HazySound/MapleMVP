const pick = <T,>(xs: T[]) => xs[Math.floor(Math.random() * xs.length)]

/** 이름 칸에 들어갈 수 있는 길이 */
const MAX = 12

/** '느긋한 핑크빈' 같은 이름 하나. 열두 자를 넘지 않는다 */
export function randomNick(): string {
  const how = pick(HOW)
  const room = MAX - how.length - 1
  const fits = WHO.filter(w => w.length <= room)
  return `${how} ${pick(fits.length ? fits : WHO)}`.slice(0, MAX).trim()
}
